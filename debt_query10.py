class CapsuleToggle(ctk.CTkFrame):
    def __init__(self, parent, options, default=0, command=None, **kwargs):
        super().__init__(parent, **kwargs)
        self.options = options
        self.command = command
        self.selected = default
        self.buttons = []

        for i, text in enumerate(options):
            btn = ctk.CTkButton(self, text=text, width=80, height=35,
                               corner_radius=20, font=("Microsoft YaHei UI", 11, "bold"))
            btn.pack(side=ctk.LEFT, padx=2)
            btn.configure(command=lambda idx=i: self.select(idx))
            self.buttons.append(btn)
        self.update_style()

    def select(self, idx):
        self.selected = idx
        self.update_style()
        if self.command:
            self.command(idx)

    def update_style(self):
        for i, btn in enumerate(self.buttons):
            if i == self.selected:
                btn.configure(fg_color="#c8a96b", text_color="#0b0907")
            else:
                btn.configure(fg_color="transparent", text_color="#8c7b5d",
                             border_width=2, border_color="#2a2520")

    def get(self):
        return self.selected


class FontSizeControl(ctk.CTkFrame):
    def __init__(self, parent, label_text, min_val, max_val, default_val, command=None, **kwargs):
        super().__init__(parent, **kwargs)
        self.min_val = min_val
        self.max_val = max_val
        self.current_val = default_val
        self.command = command

        label = ctk.CTkLabel(self, text=label_text, font=("Microsoft YaHei UI", 10))
        label.pack(side=ctk.LEFT, padx=8)

        btn_minus = ctk.CTkButton(self, text="−", width=35, height=35,
                                  corner_radius=10, font=("Microsoft YaHei UI", 14, "bold"),
                                  command=self.decrease)
        btn_minus.pack(side=ctk.LEFT, padx=2)

        self.value_label = ctk.CTkLabel(self, text=str(default_val), width=40,
                                        font=("Microsoft YaHei UI", 11, "bold"))
        self.value_label.pack(side=ctk.LEFT, padx=4)

        btn_plus = ctk.CTkButton(self, text="+", width=35, height=35,
                                 corner_radius=10, font=("Microsoft YaHei UI", 14, "bold"),
                                 command=self.increase)
        btn_plus.pack(side=ctk.LEFT, padx=2)

    def increase(self):
        if self.current_val < self.max_val:
            self.current_val += 1
            self.value_label.configure(text=str(self.current_val))
            if self.command:
                self.command(self.current_val)

    def decrease(self):
        if self.current_val > self.min_val:
            self.current_val -= 1
            self.value_label.configure(text=str(self.current_val))
            if self.command:
                self.command(self.current_val)

    def get_value(self):
        return self.current_val


