def calculate_dayun(master, year_gan, gender):
    master_yinyang = GAN_YINYANG[master]
    if (gender == "男" and master_yinyang == "阳") or (gender == "女" and master_yinyang == "阴"):
        direction = "顺行"
    else:
        direction = "逆行"
    dayun_list = []
    start_gan_idx = gan.index(master)
    start_zhi_idx = zhi.index("子")
    for i in range(8):
        if direction == "顺行":
            gan_idx = (start_gan_idx + i + 1) % 10
            zhi_idx = (start_zhi_idx + i + 1) % 12
        else:
            gan_idx = (start_gan_idx - i - 1) % 10
            zhi_idx = (start_zhi_idx - i - 1) % 12
        dayun_gan = gan[gan_idx]
        dayun_zhi = zhi[zhi_idx]
        age_start = 3 + i * 10
        dayun_list.append({
            "gan": dayun_gan, "zhi": dayun_zhi, "pillar": dayun_gan + dayun_zhi,
            "age_start": age_start, "age_end": age_start + 9
        })
    return dayun_list, direction


