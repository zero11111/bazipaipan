def get_day_gan_zhi(solar_date):
    """
    根据阳历日期计算日柱（以1900年1月1日为戊戌日基准）

    solar_date: datetime.date对象
    """
    from datetime import date

    # 基准日期：1900年1月1日为戊戌日
    base_date = date(1900, 1, 1)
    base_gan_idx = 4  # 戊
