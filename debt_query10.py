def calculate_true_solar_time(hour, minute, longitude, use_dst=False):
    """
    计算真太阳时
    优先级：北京时间 -> 夏令时修正 -> 经度修正 -> 真太阳时
    """
    standard_longitude = 120.0

    time_diff_minutes = (longitude - standard_longitude) * 4

    total_minutes = hour * 60 + minute

    if use_dst:
        total_minutes -= 60

    total_minutes += time_diff_minutes

    if total_minutes >= 1440:
        total_minutes -= 1440
    elif total_minutes < 0:
        total_minutes += 1440

    new_hour = int(total_minutes // 60)
    new_minute = int(total_minutes % 60)

    return new_hour, new_minute, time_diff_minutes



