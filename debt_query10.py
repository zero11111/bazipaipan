def query_debt_by_year(year):
    """
    根据年份查询受身债信息

    参数:
        year: 年份（整数）

    返回:
        dict: 包含受身债详细信息的字典，如果失败返回None
    """
    try:
        # 获取年柱干支
        year_gan, year_zhi = get_year_gan_zhi(year)
        ganzhi = year_gan + year_zhi

        # 查询受身债信息
        debt_info = GANZHI_DEBT_MAP.get(ganzhi)
        if not debt_info:
            return None

        # 计算元宝袋数和总价格
        total_debt = debt_info["所欠合计"]
        total_guan = total_debt * 10000
        yuanbao_bags = math.ceil(total_guan / 7000) if total_guan > 0 else 0
        yuanbao_price = 69  # 单价69元/袋
        total_cost = yuanbao_bags * yuanbao_price

        return {
            "年份": year,
            "干支": ganzhi,
            "五斗十天干助生谢恩": debt_info["五斗十天干助生谢恩"],
            "十二地支助生谢恩": debt_info["十二地支助生谢恩"],
            "十二地支受生借款": debt_info["十二地支受生借款"],
            "所欠合计": total_debt,
            "曹官": debt_info["曹官"],
            "总贯数": total_guan,
            "元宝袋数": yuanbao_bags,
            "总价格": total_cost,
            "单价": yuanbao_price
        }
    except Exception as e:
        print(f"查询受身债失败: {e}")
        return None


