        def detect_bingzheng(month_zhi, strongest_wx, weakest_wx, wuxing_count, master_wx):
            """
            检测命局病症

            参数:
            - month_zhi: 月支
            - strongest_wx: 命局最强五行
            - weakest_wx: 命局最缺五行
            - wuxing_count: 五行统计字典
            - master_wx: 日主五行

            返回: 病症列表
            """
            bingzheng_list = []

            # 1. 调候检测 (气候病)
            if month_zhi in ["亥", "子", "丑"]:  # 冬季
                bingzheng_list.append("寒湿")
            elif month_zhi in ["巳", "午", "未"]:  # 夏季
                bingzheng_list.append("燥热")
            # 注意：春季寅卯月的"微寒"不单独列为病症，进入扶抑逻辑处理

            # 2. 五行偏枯检测 (平衡病)
            # 计算总分
            total_score = sum(wuxing_count.values())
            if total_score == 0:
                return bingzheng_list

            # 【修正】检查各五行绝对分数，判断是否过旺
            # 降低阈值到3.5，更敏感地检测五行偏枯
            for wx, count in wuxing_count.items():
                if count > 3.5:  # 从4.0降低到3.5
                    if wx == get_sheng_wo(master_wx):  # 印星过旺
                        if "印重淤堵" not in bingzheng_list:
                            bingzheng_list.append("印重淤堵")
                    elif wx == master_wx:  # 比劫过旺
                        if "比劫过旺" not in bingzheng_list:
                            bingzheng_list.append("比劫过旺")
                    elif wx == get_wo_sheng(master_wx):  # 食伤过旺
                        if "食伤过重" not in bingzheng_list:
                            bingzheng_list.append("食伤过重")
                    elif wx == get_wo_ke(master_wx):  # 财星过旺
                        if "财星过重" not in bingzheng_list:
                            bingzheng_list.append("财星过重")
                    elif wx == get_ke_wo(master_wx):  # 官杀过旺
                        if "官杀过重" not in bingzheng_list:
                            bingzheng_list.append("官杀过重")

            # 【新增】特殊检测：金多水浊/印旺身强（针对秋水）
            # 即使金的分数不高，但如果生于申酉月且金是印星，也要检测
            if master_wx == "水" and month_zhi in ["申", "酉"]:
                jin_count = wuxing_count.get("金", 0)
                if jin_count > 3.0:  # 金气较旺即视为印重
                    if "金多水浊" not in bingzheng_list and "印重淤堵" not in bingzheng_list:
                        bingzheng_list.append("金多水浊")
                        print(f"  [特殊检测] 秋水金旺: 金={jin_count}分，判定为金多水浊")

            # 【新增】3. 特殊病症检测（基于《穷通宝鉴》）

            # 木多火塞：木过旺且日主为火
            if master_wx == "火" and wuxing_count.get("木", 0) > 5.0:
                if "木多火塞" not in bingzheng_list:
                    bingzheng_list.append("木多火塞")

            # 土重埋金：土过旺且日主为金，或金为用神但被土克制
            if (master_wx == "金" or get_sheng_wo(master_wx) == "金") and wuxing_count.get("土", 0) > 5.0:
                if "土重埋金" not in bingzheng_list:
                    bingzheng_list.append("土重埋金")

            # 水多木漂：水过旺且日主为木
            if master_wx == "木" and wuxing_count.get("水", 0) > 5.0:
                if "水多木漂" not in bingzheng_list:
                    bingzheng_list.append("水多木漂")

            # 火炎土焦：火过旺且日主为土
            if master_wx == "土" and wuxing_count.get("火", 0) > 5.0:
                if "火炎土焦" not in bingzheng_list:
                    bingzheng_list.append("火炎土焦")

            # 金多水浊：金过旺且日主为水（通用检测，阈值5.0）
            if master_wx == "水" and wuxing_count.get("金", 0) > 5.0:
                if "金多水浊" not in bingzheng_list:
                    bingzheng_list.append("金多水浊")

            # ... existing code ...


            # 3. 五行缺失检测（某五行为0）
            missing_elements = [wx for wx, count in wuxing_count.items() if count == 0]
