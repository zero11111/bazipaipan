def get_xun_kong(gan_zhi):
    """
    正统六甲旬空算法

    六甲旬空口诀：
    甲子旬中戌亥空，甲戌旬中申酉空，甲申旬中午未空，
    甲午旬中辰巳空，甲辰旬中寅卯空，甲寅旬中子丑空。

    原理：
    - 天干10个，地支12个，每旬10组干支
    - 旬首一定是"甲X"，剩余2个地支为空亡
    - 计算方法：找出该干支所属的旬首，再查对应的空亡
    """
    gan_idx = gan.index(gan_zhi[0])
    zhi_idx = zhi.index(gan_zhi[1])

    # 计算旬首地支索引
    # 旬首天干一定是甲(索引0)，所以旬首地支 = 当前地支 - 当前天干偏移
    xun_shou_zhi_idx = (zhi_idx - gan_idx) % 12

    # 根据旬首地支确定空亡
    kong_map = {
        0: "戌亥",   # 甲子旬
        2: "子丑",   # 甲寅旬
        4: "寅卯",   # 甲辰旬
        6: "辰巳",   # 甲午旬
        8: "午未",   # 甲申旬
        10: "申酉"   # 甲戌旬
    }

    return kong_map.get(xun_shou_zhi_idx, "")


