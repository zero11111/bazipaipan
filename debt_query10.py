        def calculate_wangshuai(master_wx, month_zhi, bangfu_count, kexie_count, bingzheng_list=None, master_gan="", dz=""):
            """
            计算旺衰（加入失令惩罚机制 + 缺印检测 + 强根加分）

            核心思路：
            - 得令者旺，失令者弱
            - 失令 + 食伤过重 = 严重泄身，即使有帮扶也是"假旺"
            - 【新增】身弱无印 = 根基不稳，必须判定为身弱
            - 【新增】日坐帝旺/羊刃 = 强根，额外加分
            - 参考《穷通宝鉴》："寅月为壬水病地，失令；若无比肩羊刃，身弱"

            参数说明：
            - master_wx: 日主五行
            - month_zhi: 月支
            - bangfu_count: 帮扶五行分数（印星+比劫的 wuxing_count 之和）
            - kexie_count: 克泄耗五行分数
            - bingzheng_list: 病症列表
            - master_gan: 日主天干（用于查长生十二宫）
            - dz: 日支（用于判断是否坐强根）
            """
            if bingzheng_list is None:
                bingzheng_list = []

            # 1. 获取月令权重
            season, season_element = get_month_season(month_zhi)

            if master_wx == season_element:
                yueling_score = 30  # 得月令
            elif get_sheng_wo(master_wx) == season_element:
                # 月令是印星（生我），也得力
                yueling_score = 25
            else:
                yueling_score = 5  # 不得月令，但有基础分

            # 2. 【修正】帮扶力量已经是分数，不需要再乘以系数
            # bangfu_count 是从 wuxing_count 获取的分数值（如土=7.0，火=1.5）
            bangfu_score = bangfu_count * 0.8  # 适当降低权重，避免过度放大

            # 3. 总能量 = 月令 + 帮扶
            total_energy = yueling_score + bangfu_score

             # 【新增】检测日支是否为帝旺/羊刃（强根）
            # 长生十二宫中，"帝旺"和"临官"为强根，应额外加分
            print(f"  [强根检测] master_gan={master_gan}, dz={dz}")
            if master_gan and dz:  # 日支存在
                day_zhi_state = SHI_ER_CHANG_SHENG.get(master_gan, {}).get(dz, "")
                print(f"  [强根检测] {master_gan}坐{dz}的状态={day_zhi_state}")
                if day_zhi_state in ["帝旺", "临官"]:
                    strong_root_bonus = 15  # 强根加分
                    total_energy += strong_root_bonus
                    print(f"  [强根加分] 日支{dz}为{day_zhi_state} → 加分{strong_root_bonus}")

            # 4. 【新增】失令惩罚机制
            # 如果不得月令且食伤过重，大幅扣分（符合《穷通宝鉴》"弱极复强"理论）
            if yueling_score < 10 and "食伤过重" in bingzheng_list:
                # 失令 + 食伤过重 = 严重泄身，惩罚性扣分
                penalty = 20
                total_energy -= penalty
                print(f"  [失令惩罚] 不得月令({yueling_score}分) + 食伤过重 → 扣分{penalty}")

            # 5. 【新增】"寒土无印"特殊检测
            # 当日主为土，生于秋冬月（申酉戌亥子丑），且印星（火）缺失或极弱时
            # 必须判定为身弱，因为"寒土不生"
            if master_wx == "土" and month_zhi in ["申", "酉", "戌", "亥", "子", "丑"]:
                fire_count = wuxing_count.get("火", 0)
                if fire_count < 1.5:  # 火极弱或缺失
                    # 强制降低总分，确保判定为身弱
                    cold_penalty = 15
                    total_energy -= cold_penalty
                    print(f"  [寒土无印] 土生{month_zhi}月，火={fire_count}分 → 扣分{cold_penalty}（寒土不生）")

            # 6. 【新增】"金多水浊/水冷金寒"检测
            # 【新增】"金多水浊/水冷金寒"检测
            # 当日主为水，生于秋冬月，且印星（金）过旺但无比劫帮身时
            # 虽然印旺，但"金寒水冷"，实际身弱
            if master_wx == "水" and month_zhi in ["申", "酉", "亥", "子"]:
                jin_count = wuxing_count.get("金", 0)
                shui_count = wuxing_count.get("水", 0)
                if jin_count > 3.0 and shui_count < 2.0:
                    # 印旺身弱，需要火来暖局
                    cold_water_penalty = 10
                    total_energy -= cold_water_penalty
                    print(f"  [金寒水冷] 金={jin_count}分，水={shui_count}分 → 扣分{cold_water_penalty}")

            # 【新增】"官杀贴身克身"检测
            # 当日主身弱且官杀过旺时，即使有帮扶，也应判定为身弱
            ke_master_wx = get_ke_wo(master_wx)  # 克我者（官杀）
            if "官杀过重" in bingzheng_list or (ke_master_wx and wuxing_count.get(ke_master_wx, 0) > 4.0):
                # 官杀过旺，严重克身，惩罚性扣分
                guan_sha_penalty = 15
                total_energy -= guan_sha_penalty
                print(f"  [官杀克身] 官杀{ke_master_wx}={wuxing_count.get(ke_master_wx, 0)}分 → 扣分{guan_sha_penalty}")

            # 【新增】"印旺生身"检测
            # 当印星过旺（>4.0）且日主得令或中和时，应判定为身旺
            sheng_master_wx = get_sheng_wo(master_wx)  # 生我者（印星）
            if wuxing_count.get(sheng_master_wx, 0) > 4.0 and yueling_score >= 20:
                # 印星过旺且得令，加分
                yin_wang_bonus = 15
                total_energy += yin_wang_bonus
                print(f"  [印旺生身] 印星{sheng_master_wx}={wuxing_count.get(sheng_master_wx, 0)}分，得令{yueling_score}分 → 加分{yin_wang_bonus}")

            # 【新增】"比劫助力"检测
            # 当比劫过旺（>3.5）时，额外加分
            if wuxing_count.get(master_wx, 0) > 3.5:
                bi_jie_bonus = 10
                total_energy += bi_jie_bonus
                print(f"  [比劫助力] 比劫{master_wx}={wuxing_count.get(master_wx, 0)}分 → 加分{bi_jie_bonus}")

            # 【新增】"建禄格/归禄格"检测
            # 当日主生于临官月（寅申巳亥），且地支有禄地时，应判定为身旺
            lin_guan_zhis = {"甲": "寅", "乙": "卯", "丙": "巳", "丁": "午", "戊": "巳",
                           "己": "午", "庚": "申", "辛": "酉", "壬": "亥", "癸": "子"}
            if master_gan and month_zhi == lin_guan_zhis.get(master_gan, ""):
                jian_lu_bonus = 20  # 建禄格大幅加分
                total_energy += jian_lu_bonus
                print(f"  [建禄格] {master_gan}生{month_zhi}月，得禄 → 加分{jian_lu_bonus}")

            # 7. 调试输出
            print(f"  [旺衰计算细节] 月令:{month_zhi}({season}), 月令得分:{yueling_score}, 帮扶分数:{bangfu_count}, 帮扶加权:{bangfu_score:.1f}, 总分:{total_energy:.1f}")

            # 8. 判定结果（调整阈值）
            if total_energy >= 50:
                return "身旺"
            elif total_energy <= 25:
                return "身弱"
            else:
                return "中和"




